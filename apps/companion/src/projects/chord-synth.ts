/** Trusted, opt-in demo sound. Never exposed to generated project JavaScript. */
export const CHORDS = {
  chord_c: { label: 'Cmaj7', notes: [60, 64, 67, 71] },
  chord_am: { label: 'Am7', notes: [57, 60, 64, 67] },
  chord_f: { label: 'Fmaj7', notes: [53, 57, 60, 64] },
  chord_g: { label: 'G7', notes: [55, 59, 62, 65] },
} as const;
export type ChordId = keyof typeof CHORDS;
export interface ChordPlayback { id: ChordId; label: string; notes: readonly number[]; noteLabels: readonly string[] }
const CHORD_IDS = Object.keys(CHORDS) as ChordId[];
const COUNTERS = [...CHORD_IDS, 'silence'] as const;
const NOTE_NAMES = ['C', 'C♯', 'D', 'E♭', 'E', 'F', 'F♯', 'G', 'A♭', 'A', 'B♭', 'B'];

export function midiFrequency(note: number): number { return 440 * 2 ** ((note - 69) / 12); }
export function noteName(note: number): string { return `${NOTE_NAMES[((note % 12) + 12) % 12]}${Math.floor(note / 12) - 1}`; }
export function chordNotes(id: ChordId): readonly number[] { return CHORDS[id].notes; }
function counters(values: Record<string, number>): Record<string, number> {
  return Object.fromEntries(COUNTERS.map(id => [id, Number.isSafeInteger(values[id]) && values[id]! >= 0 ? values[id]! : 0]));
}
interface Voice { oscillator: OscillatorNode; gain: GainNode }

/**
 * The host binds a project/revision and owns visibility, readiness and disconnect
 * checks. Only its explicit user gesture may call enable(). Snapshots never play
 * old chords, and each new chord replaces the previous bounded four-note voice.
 */
export class ChordSynth {
  private context?: AudioContext;
  private allowed = false;
  private disposed = false;
  private generation = 0;
  private enabling?: Promise<void>;
  private baseline?: Record<string, number>;
  private readonly voices = new Set<Voice>();
  private playback?: ChordPlayback;
  constructor(
    private readonly createContext: () => AudioContext = () => new AudioContext({ latencyHint: 'interactive' }),
    private readonly onChord?: (chord: ChordPlayback | undefined) => void,
    private readonly onUnavailable?: () => void,
  ) {}
  get enabled(): boolean { return this.allowed && !this.disposed && this.context?.state === 'running'; }
  get current(): ChordPlayback | undefined { return this.playback; }

  /** No sound is generated by unlocking, including after an async resume. */
  async enable(): Promise<void> {
    if (this.disposed) throw new Error('Chord synth has been disposed.');
    if (this.enabled) return;
    if (this.enabling) return this.enabling;
    const generation = ++this.generation;
    const context = this.context ??= this.createContext();
    context.onstatechange = () => {
      if (context !== this.context || !this.allowed || context.state === 'running') return;
      // A browser/OS audio interruption invalidates readiness, even if the
      // context later resumes itself. The host must withdraw its preview lease.
      this.stop(); this.onUnavailable?.();
    };
    this.allowed = false;
    const operation = (async () => {
      try { await context.resume(); }
      catch (error) { if (generation === this.generation && !this.disposed) throw error; return; }
      if (generation !== this.generation || this.disposed) return;
      if (context.state !== 'running') throw new Error('Sound is still blocked. Click Enable sound again.');
      this.allowed = true;
    })();
    this.enabling = operation;
    try { await operation; }
    finally { if (this.enabling === operation) this.enabling = undefined; }
  }

  /** A new project/revision requires a fresh explicit audio unlock. */
  bind(values: Record<string, number> = {}): void { this.disable(); this.baseline = counters(values); }
  reset(values: Record<string, number> = {}): void { this.bind(values); }

  consume(values: Record<string, number>): void {
    const next = counters(values), previous = this.baseline;
    this.baseline = next;
    if (!previous || !this.enabled) return;
    // A Stop in the same canonical update always wins over a chord.
    if (next.silence! > previous.silence!) { this.clearVoices(); return; }
    // Counter resets, jumped counters and ambiguous combined snapshots are state
    // restoration, not a queue of musical events to replay on reconnect/unlock.
    if (COUNTERS.some(id => next[id]! < previous[id]!)) { this.clearVoices(); return; }
    const changed = CHORD_IDS.filter(id => next[id]! > previous[id]!);
    if (changed.length !== 1) return;
    const id = changed[0]!;
    if (next[id]! !== previous[id]! + 1) return;
    this.play(id);
  }

  stop(): void {
    ++this.generation; this.enabling = undefined; this.allowed = false;
    this.clearVoices();
  }
  disable(): void { this.stop(); }
  dispose(): void {
    if (this.disposed) return;
    this.stop(); this.disposed = true; this.baseline = undefined;
    const context = this.context; this.context = undefined;
    if (context) {
      context.onstatechange = null;
      if (context.state !== 'closed') void context.close().catch(() => {});
    }
  }

  private play(id: ChordId): void {
    const context = this.context;
    if (!context || !this.enabled) return;
    this.clearVoices();
    const now = context.currentTime;
    try {
      for (const note of chordNotes(id)) {
        const oscillator = context.createOscillator(), gain = context.createGain();
        const voice = { oscillator, gain }; this.voices.add(voice);
        oscillator.type = 'triangle'; oscillator.frequency.setValueAtTime(midiFrequency(note), now);
        // Four voices sum to a modest fixed peak; every voice ends in <1 second.
        gain.gain.setValueAtTime(0, now);
        gain.gain.linearRampToValueAtTime(0.035, now + 0.025);
        gain.gain.linearRampToValueAtTime(0.022, now + 0.15);
        gain.gain.linearRampToValueAtTime(0, now + 0.78);
        oscillator.connect(gain); gain.connect(context.destination);
        oscillator.onended = () => {
          if (!this.voices.delete(voice)) return;
          oscillator.disconnect(); gain.disconnect();
          if (!this.voices.size) this.setPlayback(undefined);
        };
        oscillator.start(now); oscillator.stop(now + 0.82);
      }
      const chord = CHORDS[id];
      this.setPlayback({ id, label: chord.label, notes: chord.notes, noteLabels: chord.notes.map(noteName) });
    } catch (error) {
      this.disable();
      throw error;
    }
  }
  private setPlayback(value: ChordPlayback | undefined): void {
    if (!value && !this.playback) return;
    this.playback = value; this.onChord?.(value);
  }
  private clearVoices(): void {
    for (const { oscillator, gain } of this.voices) {
      oscillator.onended = null;
      try { oscillator.stop(this.context?.currentTime ?? 0); } catch { /* Already stopped/never started. */ }
      oscillator.disconnect(); gain.disconnect();
    }
    this.voices.clear(); this.setPlayback(undefined);
  }
}
